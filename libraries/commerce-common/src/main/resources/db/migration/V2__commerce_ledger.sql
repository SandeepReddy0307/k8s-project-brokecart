CREATE TABLE event_outbox (sequence_number BIGINT GENERATED BY DEFAULT AS IDENTITY, event_id VARCHAR(100) PRIMARY KEY, topic VARCHAR(100) NOT NULL, aggregate_id VARCHAR(100) NOT NULL, payload TEXT NOT NULL, published BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP NOT NULL);
CREATE INDEX outbox_pending ON event_outbox(published, created_at);

