import { test, expect } from '@playwright/test';
test('complete commerce UI', async ({page}, info) => {
  test.skip(process.env.FULL_COMMERCE !== '1', 'Run tests/browser_flow.py for real application workflows.');
  test.setTimeout(120000);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:5173');
  await expect(page.getByRole('button',{name:'Add Cloud Nine Headphones to cart'})).toBeVisible();
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('button',{name:'New here? Create an account'}).click();
  await page.getByLabel('Email',{exact:true}).fill(`browser-${info.project.name}-${Date.now()}@example.test`);
  await page.getByLabel('Password',{exact:true}).fill('BrowserCommerceTests123!');
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page.getByRole('button',{name:'View my orders'})).toBeVisible();
  await page.getByRole('button',{name:'Close account panel'}).click();
  await page.getByRole('button',{name:'Add Cloud Nine Headphones to cart'}).click();
  await page.getByRole('button',{name:/Your cart/}).click();
  await page.getByRole('button',{name:'Continue to checkout'}).click();
  await page.getByLabel('Delivery address').fill('123 Browser Test Street, Local City 12345');
  await page.getByRole('button',{name:'Place order'}).click();
  await expect(page.locator('.order-card .state')).toHaveText('CONFIRMED',{timeout:45000});
  await page.getByRole('button',{name:'Track shipment'}).click();
  await expect(page.locator('.tracking')).toContainText('BC-');
  await page.screenshot({path:`/tmp/brokecart-orders-${info.project.name}.png`,fullPage:true});
  await page.getByRole('button',{name:'Cancel order'}).click();
  await expect(page.locator('.order-card .state')).toHaveText('CANCELLED',{timeout:45000});
  await page.getByRole('button',{name:'Close account panel'}).click();
  await page.getByRole('button',{name:'My account',exact:true}).click();
  await page.getByRole('button',{name:'Sign out'}).click();
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByLabel('Email',{exact:true}).fill('operator@example.test');
  await page.getByLabel('Password',{exact:true}).fill('ApplicationTestsOnly123!');
  await page.getByRole('dialog').getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('button',{name:'Open operations'}).click();
  await expect(page.getByRole('heading',{name:'BrokeCart operations'})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Stock & prices'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Add 10'})).toHaveCount(8);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:`/tmp/brokecart-operations-${info.project.name}.png`,fullPage:true});
  expect(errors).toEqual([]);
});
